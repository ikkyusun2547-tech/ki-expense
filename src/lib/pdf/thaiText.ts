// แก้ปัญหา react-pdf กับสระอำ (U+0E33)
// ฟอนต์แตก "ำ" เป็น 2 glyph (นิคหิต ํ U+0E4D + สระอา า U+0E32) แต่ react-pdf นับตัวอักษร 1:1 กับ glyph
// ทำให้ตัดท้ายข้อความหาย (เช่น "จำกัด" เหลือ "จำก") — แยกให้เองก่อนส่งเข้า PDF จึงตรงกัน 1:1
// ลำดับที่ถูกเมื่อมีวรรณยุกต์: พยัญชนะ + ํ + วรรณยุกต์ + า (เช่น น้ำ → น ํ ้ า) เพื่อให้นิคหิตอยู่ใต้วรรณยุกต์
export function thaiPdfText(text: string): string {
  return text.replace(/([่-๋]?)ำ/g, "ํ$1า");
}
