import { describe, expect, it } from "vitest";
import { bahtText } from "@/lib/thai/bahtText";

describe("bahtText", () => {
  it.each([
    // ค่าที่กำหนดในสเปก
    ["749", "เจ็ดร้อยสี่สิบเก้าบาทถ้วน"],
    ["631.30", "หกร้อยสามสิบเอ็ดบาทสามสิบสตางค์"],
    ["1068.93", "หนึ่งพันหกสิบแปดบาทเก้าสิบสามสตางค์"],
    // กรณีขอบ
    ["0", "ศูนย์บาทถ้วน"],
    ["1", "หนึ่งบาทถ้วน"],
    ["10", "สิบบาทถ้วน"],
    ["11", "สิบเอ็ดบาทถ้วน"],
    ["20", "ยี่สิบบาทถ้วน"],
    ["21", "ยี่สิบเอ็ดบาทถ้วน"],
    ["100", "หนึ่งร้อยบาทถ้วน"],
    ["101", "หนึ่งร้อยเอ็ดบาทถ้วน"],
    ["110", "หนึ่งร้อยสิบบาทถ้วน"],
    ["1000", "หนึ่งพันบาทถ้วน"],
    ["10000", "หนึ่งหมื่นบาทถ้วน"],
    ["100000", "หนึ่งแสนบาทถ้วน"],
    ["1000000", "หนึ่งล้านบาทถ้วน"],
    ["1000001", "หนึ่งล้านเอ็ดบาทถ้วน"],
    ["11000000", "สิบเอ็ดล้านบาทถ้วน"],
    ["21500000", "ยี่สิบเอ็ดล้านห้าแสนบาทถ้วน"],
    ["0.01", "หนึ่งสตางค์"],
    ["0.50", "ห้าสิบสตางค์"],
    ["5.21", "ห้าบาทยี่สิบเอ็ดสตางค์"],
    ["1,068.93", "หนึ่งพันหกสิบแปดบาทเก้าสิบสามสตางค์"],
  ])("%s → %s", (amount, expected) => {
    expect(bahtText(amount)).toBe(expected);
  });

  it("รับ number และ Prisma Decimal", () => {
    expect(bahtText(631.3)).toBe("หกร้อยสามสิบเอ็ดบาทสามสิบสตางค์");
    expect(bahtText({ toFixed: () => "749.00" })).toBe("เจ็ดร้อยสี่สิบเก้าบาทถ้วน");
  });

  it("ปฏิเสธยอดที่ไม่ใช่ตัวเลข", () => {
    expect(() => bahtText("abc")).toThrow();
  });
});
